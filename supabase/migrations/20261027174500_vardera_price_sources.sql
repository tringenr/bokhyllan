-- Värdera fas 1: stöd för flera sajt-priser per bok, osäkerhet, hetta och
-- villkorskommentar. En rad per bok+sajt i sell_price_sources, panelen i
-- appen expanderar och visar dem under bokens rad i sell_items.
--
-- wanted_ad_url skapas redan nu (fält för annons som söker boken) men fylls
-- inte i fas 1 - det väntar tills vi vet om det förekommer i praktiken på
-- Studentapan/Bokbörsen/Tradera.

alter table public.sell_items
  add column if not exists estimated_value integer,
  add column if not exists uncertainty text check (uncertainty in ('lag','medel','hog')),
  add column if not exists heat_score text check (heat_score in ('het','medel','lag','kolla')),
  add column if not exists heat_reason text,
  add column if not exists condition_note text,
  add column if not exists wanted_ad_url text,
  add column if not exists last_checked_at timestamptz;

-- En rad per bok per bibliotek - omsökning uppdaterar befintlig rad istället
-- för att skapa en dubblett. De 31 befintliga raderna har redan unika
-- book_id, så regeln läggs på utan konflikt.
create unique index if not exists sell_items_library_book_uidx
  on public.sell_items (library_id, book_id)
  where book_id is not null;

create table public.sell_price_sources (
  id bigint generated by default as identity primary key,
  sell_item_id bigint not null references public.sell_items(id) on delete cascade,
  site text not null check (site in ('studentapan','bokborsen','tradera')),
  price integer,
  url text,
  fetched_at timestamptz not null default now()
);

alter table public.sell_price_sources enable row level security;

create policy sell_price_sources_select on public.sell_price_sources
  for select using (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_sources.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );

create policy sell_price_sources_insert on public.sell_price_sources
  for insert with check (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_sources.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );

create policy sell_price_sources_update on public.sell_price_sources
  for update using (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_sources.sell_item_id
        and public.is_library_member(si.library_id)
    )
  ) with check (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_sources.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );

create policy sell_price_sources_delete on public.sell_price_sources
  for delete using (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_sources.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );
