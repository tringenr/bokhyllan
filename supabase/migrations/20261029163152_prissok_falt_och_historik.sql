--
-- Statusar (visningsnamn i appen inom parentes, satt av Design):
--   bekraftat    - Kontrollerat (en människa, t.ex. Chrome-steget eller Campus-rundan)
--   automatiskt  - Okontrollerat (sparat av sökningen, ingen har kollat)
--   vantar       - Väntar på kontroll (trolig sida, inget säkert pris)
--   osakert      - Varierande pris (olika träffar mellan sökomgångar - spann, aldrig ett gissat tal)
--   ingen_traff  - Inget hittat (sökt, inget funnet - dold som standard)
--
-- Beslutat 29/10: en ny sökning ERSÄTTER det aktuella priset (oavsett status).
-- Det ersatta sparas i sell_price_history, aldrig raderat.

alter table public.sell_items
  add column if not exists price_status text
    check (price_status in ('bekraftat','automatiskt','vantar','osakert','ingen_traff')),
  add column if not exists price_low integer,
  add column if not exists price_high integer,
  add column if not exists searched_at timestamptz;

-- Bakåtfyllnad: de 39 raderna som redan är markerade granskade (checked,
-- inklusive de 11 från Campusbokhandeln-rundan 27/10 som redan har en
-- sell_price_sources-rad) räknas som kontrollerade - de ska alltid visas
-- med bekräftelsedialog innan de söks om, aldrig skrivas över tyst.
update public.sell_items set price_status='bekraftat' where checked;

-- sell_price_sources blir "aktuellt läge", en rad per bok+sajt - en ny
-- sökning uppdaterar raden (upsert on conflict) istället för att skapa en
-- dubblett. page_title/title_match sparas för spårbarhet (lärdom 1-2 i
-- rapporten: lita aldrig bara på textutdraget).
alter table public.sell_price_sources
  add column if not exists page_title text,
  add column if not exists title_match text check (title_match in ('stark','svag')),
  add column if not exists status text
    check (status in ('bekraftat','automatiskt','vantar','osakert'));

create unique index if not exists sell_price_sources_item_site_uidx
  on public.sell_price_sources (sell_item_id, site);

-- De 11 befintliga Campusbokhandeln-raderna är människogranskade.
update public.sell_price_sources set status='bekraftat' where status is null;

-- Historik: det en omsökning ersatte, aldrig raderat. Fylls av
-- edge-funktionen (läs gammal rad -> skriv hit -> skriv över den aktuella),
-- inte av en trigger - hålls i samma kod som matchningslogiken.
create table public.sell_price_history (
  id bigint generated by default as identity primary key,
  sell_item_id bigint not null references public.sell_items(id) on delete cascade,
  site text not null,
  price integer,
  url text,
  page_title text,
  status text not null check (status in ('bekraftat','automatiskt','vantar','osakert')),
  replaced_at timestamptz not null default now()
);

alter table public.sell_price_history enable row level security;

create policy sell_price_history_select on public.sell_price_history
  for select using (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_history.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );

create policy sell_price_history_insert on public.sell_price_history
  for insert with check (
    exists (
      select 1 from public.sell_items si
      where si.id = sell_price_history.sell_item_id
        and public.is_library_member(si.library_id)
    )
  );
